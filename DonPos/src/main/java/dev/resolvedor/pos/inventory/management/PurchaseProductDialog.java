    private void okButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_okButtonActionPerformed

        if (!validateData()) {
            return;
        }

        tax = taxeslogic.getTaxInfo(selectedProduct.getTaxCategoryID(), null);

        selectedProduct.setQuantity(Double.parseDouble(txtQuantiy.getText()));
        selectedProduct.setTotalCost(Read.currency(txtTotalCost.getText().trim()));

        double costWithTax = selectedProduct.getTotalCost() / selectedProduct.getQuantity();
        double taxValue = tax.getRate() + 1;
        selectedProduct.setPriceBuy(costWithTax / taxValue);
        selectedProduct.setLot(modelLot.getSelectedKey().toString());
        doClose(RET_OK);
    }//GEN-LAST:event_okButtonActionPerformed

    private boolean validateData() {
        // El SRI exige el sustento por item, no por documento, asi que sin el
        // la linea no sirve para armar la retencion.
        if (getTaxSupport() == null) {
            JOptionPane.showMessageDialog(this,
                    AppLocal.getIntString("message.fillallfields"),
                    AppLocal.getIntString("label.taxSupport"),
                    JOptionPane.ERROR_MESSAGE);
            return false;
        }

        if (!StringUtils.isNumber(txtQuantiy.getText().trim())) {
            JOptionPane.showMessageDialog(this, LocalRes.getIntString("message.numericamount"), AppLocal.getIntString("label.units2"), JOptionPane.ERROR_MESSAGE);
            return false;
        } else {
            var validNumber = Double.parseDouble(txtQuantiy.getText().trim());
            if (validNumber <= 0) {
                JOptionPane.showMessageDialog(this, LocalRes.getIntString("exception.nonegativenumberorzero"), AppLocal.getIntString("label.units2"), JOptionPane.ERROR_MESSAGE);
                return false;
            }
        }

        if (selectedProduct == null) {
            JOptionPane.showMessageDialog(this, AppLocal.getIntString("message.noproduct"), AppLocal.getIntString("label.stockproduct"), JOptionPane.ERROR_MESSAGE);
            return false;
        }

        if (modelLot.getSelectedKey() == null) {
            JOptionPane.showMessageDialog(this, LocalRes.getIntString("exception.noLot"), AppLocal.getIntString("label.lot"), JOptionPane.ERROR_MESSAGE);
            return false;
        }

        if (Read.currency(txtTotalCost.getText().trim()) == null) {
            JOptionPane.showMessageDialog(this, LocalRes.getIntString("message.numericTotal"), AppLocal.getIntString("label.total"), JOptionPane.ERROR_MESSAGE);
            return false;
        } else {
            var validNumber = Read.currency(txtTotalCost.getText().trim());
            if (validNumber < 0) {
                JOptionPane.showMessageDialog(this, LocalRes.getIntString("exception.nonegativenumberorzero"), AppLocal.getIntString("label.total"), JOptionPane.ERROR_MESSAGE);
                return false;
            }
        }

        try {
            if (dlSales.isProductBundle(selectedProduct.getID())) {
                JOptionPane.showMessageDialog(this, LocalRes.getIntString("message.product.bundle.purchase"), AppLocal.getIntString("label.stockproduct"), JOptionPane.ERROR_MESSAGE);
                return false;
            }
        } catch (BasicException ex) {
            log.error(PurchaseProductDialog.class.getName() + " isProductBundle " + ex);
            return false;
        }

        return true;
    }

