    private void findProduct() {
        lpr = new ListProviderCreator(dlSales.getProductListByName(txtProductName.getText()));

        try {
            jListProducts.setModel(new PurchaseProductDialog.MyListData(lpr.loadData()));
            if (jListProducts.getModel().getSize() > 0) {
                jListProducts.setSelectedIndex(0);
                jListProducts.requestFocus();
            }
        } catch (BasicException e) {
        }
    }

