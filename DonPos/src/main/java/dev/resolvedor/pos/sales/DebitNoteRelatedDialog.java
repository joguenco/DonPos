    private void okButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_okButtonActionPerformed
        if (!validateData()) {
            return;
        }

        doClose(RET_OK);
    }//GEN-LAST:event_okButtonActionPerformed

    private boolean validateData() {
        if (selectedTicket == null) {
            JOptionPane.showMessageDialog(this, AppLocal.getIntString("Menu.UserNoSales"), AppLocal.getIntString("label.debit.note"), JOptionPane.ERROR_MESSAGE);
            return false;
        }

        return true;
    }
