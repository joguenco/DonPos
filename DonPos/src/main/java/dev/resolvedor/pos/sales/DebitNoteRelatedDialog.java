    private void cmdFindTicketActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmdFindTicketActionPerformed
        try {
//            var result = dlSales.getTicketByCustomer()
//                    .list(new Object[]{ticket.getCustomerId()});
            lpr = new ListProviderCreator(dlSales.getTicketByCustomer(debitNoteTicket.getCustomerId()));
            jListTickets.setModel(new DebitNoteRelatedDialog.MyListData(lpr.loadData()));

        } catch (BasicException ex) {
            log.error(DebitNoteRelatedDialog.class.getName() + " cmdFindTicketActionPerformed " + ex.getMessage());
        }
    }//GEN-LAST:event_cmdFindTicketActionPerformed

